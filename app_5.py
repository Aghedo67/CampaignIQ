# ── Tab 4: Budget Optimiser ──────────────────────────────────────────────────────
with tab4:
    st.subheader("Budget Optimiser")
    st.write("Find the profit-maximising number of customers to target "
             "given your campaign economics.")

    col1, col2 = st.columns(2)
    with col1:
        cost_per_email  = st.number_input("Cost per email (£)", min_value=0.50,
                                          max_value=20.0, value=2.0, step=0.50)
        value_per_visit = st.number_input("Value per incremental visit (£)", min_value=1.0,
                                          max_value=100.0, value=15.0, step=1.0)
    with col2:
        st.info(
            "**Value per incremental visit** = estimated revenue generated when an "
            "incremental visitor converts. Use your average order value × conversion "
            "rate from site analytics, or a conservative LTV fraction."
        )

    if "uplift_score" not in df.columns:
        st.warning("Upload `hillstrom_final.csv` to enable this calculator.")
    else:
        df_opt = df.sort_values("uplift_score", ascending=False).reset_index(drop=True)
        N_t_total = (df["treatment_any"] == 1).sum()
        N_c_total = (df["treatment_any"] == 0).sum()

        thresholds = np.linspace(0.01, 1.0, 100)
        rows = []
        for pct in thresholds:
            n   = int(len(df_opt) * pct)
            top = df_opt.iloc[:n]
            n_t = (top["treatment_any"] == 1).sum()
            n_c = (top["treatment_any"] == 0).sum()
            y_t = top[top["treatment_any"] == 1]["visit"].sum()
            y_c = top[top["treatment_any"] == 0]["visit"].sum()
            if n_t > 0 and n_c > 0:
                incr    = (y_t / N_t_total - y_c / N_c_total) * N_t_total
                revenue = incr * value_per_visit
                cost    = n * cost_per_email
                net_roi = revenue - cost
            else:
                revenue = cost = net_roi = 0
            rows.append({"pct": pct, "n": n, "revenue": revenue,
                         "cost": cost, "net_roi": net_roi})

        opt_df     = pd.DataFrame(rows)
        best_idx   = opt_df["net_roi"].idxmax()
        best       = opt_df.loc[best_idx]

        st.divider()
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Optimal customers to target", f"{int(best['n']):,}")
        c2.metric("% of total customer base",    f"{best['pct']*100:.0f}%")
        c3.metric("Estimated gross revenue",      f"£{best['revenue']:,.0f}")
        c4.metric("Maximum net ROI",              f"£{best['net_roi']:,.0f}",
                  delta="at optimal threshold", delta_color="normal")

        st.divider()
        col_a, col_b = st.columns(2)

        with col_a:
            fig_roi = go.Figure()
            fig_roi.add_trace(go.Scatter(x=opt_df["pct"]*100, y=opt_df["net_roi"],
                                         mode="lines", name="Net ROI",
                                         line=dict(color=BRAND, width=2.5)))
            fig_roi.add_trace(go.Scatter(x=opt_df["pct"]*100, y=opt_df["revenue"],
                                         mode="lines", name="Gross Revenue",
                                         line=dict(color=GREEN, width=2, dash="dash")))
            fig_roi.add_trace(go.Scatter(x=opt_df["pct"]*100, y=-opt_df["cost"],
                                         mode="lines", name="Campaign Cost (−)",
                                         line=dict(color=RED, width=2, dash="dash")))
            fig_roi.add_vline(x=best["pct"]*100, line_dash="dot", line_color=ORANGE,
                              annotation_text=f"Optimal: {best['pct']*100:.0f}%")
            fig_roi.add_hline(y=0, line_color="black", line_width=1)
            fig_roi.update_layout(
                title="Net ROI vs Targeting Threshold",
                xaxis_title="% of Customers Targeted",
                yaxis_title="£",
                xaxis_ticksuffix="%",
                yaxis_tickprefix="£",
                legend=dict(x=0.01, y=0.99),
                plot_bgcolor="#F9F9F9",
            )
            st.plotly_chart(fig_roi, use_container_width=True)

        with col_b:
            sensitivity = []
            for cpe in [0.50, 1.00, 2.00, 5.00, 10.00]:
                for vpv in [5.0, 10.0, 15.0, 25.0, 50.0]:
                    r2 = []
                    for pct in thresholds:
                        n   = int(len(df_opt) * pct)
                        top = df_opt.iloc[:n]
                        n_t2 = (top["treatment_any"] == 1).sum()
                        n_c2 = (top["treatment_any"] == 0).sum()
                        y_t2 = top[top["treatment_any"] == 1]["visit"].sum()
                        y_c2 = top[top["treatment_any"] == 0]["visit"].sum()
                        if n_t2 > 0 and n_c2 > 0:
                            incr2 = (y_t2/N_t_total - y_c2/N_c_total) * N_t_total
                            r2.append(incr2 * vpv - n * cpe)
                        else:
                            r2.append(0)
                    sensitivity.append({
                        "Cost/email": f"£{cpe:.2f}",
                        "Value/visit": f"£{vpv:.0f}",
                        "Max Net ROI": f"£{max(r2):,.0f}",
                        "Positive?": "✅" if max(r2) > 0 else "❌",
                    })
            sens_df = pd.DataFrame(sensitivity)
            st.markdown("**Sensitivity: max net ROI under different cost/value assumptions**")
            st.dataframe(sens_df, use_container_width=True, hide_index=True)